/* IT Device Manager V1.3.5 - cleanup legacy sample serial numbers.
   Only DEMO-SN-* values are changed. User-entered real serials are untouched. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

UPDATE dbo.Devices
SET SerialNumber = CASE Code
    WHEN N'TB001' THEN N'DL7020-260001'
    WHEN N'TB002' THEN N'DL5450-260002'
    WHEN N'TB003' THEN N'HP4003-260003'
    WHEN N'TB004' THEN N'DP2425-260004'
    WHEN N'TB005' THEN N'CBS350-260005'
    WHEN N'TB006' THEN N'HPEML30-260006'
    WHEN N'TB007' THEN N'APC1500-260007'
    WHEN N'TB008' THEN N'HK4MP-260008'
    WHEN N'TB009' THEN N'RJX628-260009'
    WHEN N'TB010' THEN N'ZDS2208-260010'
    ELSE SerialNumber
END
WHERE SerialNumber LIKE N'DEMO-SN-%'
  AND Code IN (N'TB001',N'TB002',N'TB003',N'TB004',N'TB005',N'TB006',N'TB007',N'TB008',N'TB009',N'TB010');

-- Also handle databases that have not yet applied the TBM -> TB migration.
UPDATE dbo.Devices
SET SerialNumber = CASE Code
    WHEN N'TBM001' THEN N'DL7020-260001'
    WHEN N'TBM002' THEN N'DL5450-260002'
    WHEN N'TBM003' THEN N'HP4003-260003'
    WHEN N'TBM004' THEN N'DP2425-260004'
    WHEN N'TBM005' THEN N'CBS350-260005'
    WHEN N'TBM006' THEN N'HPEML30-260006'
    WHEN N'TBM007' THEN N'APC1500-260007'
    WHEN N'TBM008' THEN N'HK4MP-260008'
    WHEN N'TBM009' THEN N'RJX628-260009'
    WHEN N'TBM010' THEN N'ZDS2208-260010'
    ELSE SerialNumber
END
WHERE SerialNumber LIKE N'DEMO-SN-%'
  AND Code IN (N'TBM001',N'TBM002',N'TBM003',N'TBM004',N'TBM005',N'TBM006',N'TBM007',N'TBM008',N'TBM009',N'TBM010');

COMMIT TRANSACTION;

SELECT Code, Name, SerialNumber
FROM dbo.Devices
ORDER BY Code;
